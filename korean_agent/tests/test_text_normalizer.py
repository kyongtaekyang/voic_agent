import pytest

from realtime_server.text_normalizer import native_attr, normalize, sino


@pytest.mark.parametrize("n,expected", [
    (0, "영"), (1, "일"), (10, "십"), (11, "십일"), (20, "이십"), (100, "백"), (105, "백오"), (1000, "천"),
    (1234, "천이백삼십사"), (10000, "만"), (20000, "이만"), (10001, "만일"), (110000, "십일만"),
    (100000000, "일억"), (2026, "이천이십육"),
])
def test_sino(n, expected):
    assert sino(n) == expected


@pytest.mark.parametrize("n,expected", [
    (1, "한"), (2, "두"), (3, "세"), (4, "네"), (10, "열"), (11, "열한"), (20, "스무"), (21, "스물한"),
    (35, "서른다섯"), (99, "아흔아홉"), (100, "백"),
])
def test_native_attr(n, expected):
    assert native_attr(n) == expected


@pytest.mark.parametrize("text,expected", [
    # 1단계 왕복 인식에서 모든 TTS 가 틀린 문장
    ("사과 3개와 배 10개를 샀어요. 10:30에 만나요.", "사과 세 개와 배 열 개를 샀어요. 열 시 삼십 분에 만나요."),
    # 고유어 단위
    ("학생이 20명 있어요.", "학생이 스무 명 있어요."),
    ("저는 9살이에요.", "저는 아홉 살이에요."),
    ("3시간 동안 했어요.", "세 시간 동안 했어요."),
    ("1번째 문제예요.", "첫 번째 문제예요."),
    ("2번째 문제예요.", "두 번째 문제예요."),
    ("한 번만 더 해 볼까요?", "한 번만 더 해 볼까요?"),
    ("3~5개 고르세요.", "세 개에서 다섯 개 고르세요."),
    # 한자어 단위
    ("30분 쉬어요.", "삼십 분 쉬어요."),
    ("3개월 걸려요.", "삼 개월 걸려요."),
    ("1,500원이에요.", "천오백 원이에요."),
    ("2026년 6월 10일", "이천이십육 년 유월 십 일"),
    ("10월에 만나요.", "시월에 만나요."),
    ("50%예요.", "오십 퍼센트예요."),
    ("5km 걸었어요.", "오 킬로미터 걸었어요."),
    ("3학년 2반", "삼 학년 이 반"),
    # 시각
    ("9:00에 시작해요.", "아홉 시에 시작해요."),
    ("12:05", "열두 시 오 분"),
    # 소수, 수식
    ("3.5점이에요.", "삼 점 오점이에요."),
    ("3+2=5", "삼 더하기 이는 오"),
    ("10 - 3 = 7", "십 빼기 삼은 칠"),
    ("4×2=8", "사 곱하기 이는 팔"),
    # 단위 없는 수
    ("정답은 7이에요.", "정답은 칠이에요."),
    # 이미 읽는 형태: 그대로
    ("지금은 열 시 삼십 분이에요.", "지금은 열 시 삼십 분이에요."),
    # 기호 제거
    ("**잘했어요!** 😊", "잘했어요!"),
    ("사과(빨간색)가 있어요.", "사과가 있어요."),
])
def test_normalize(text, expected):
    assert normalize(text) == expected


def test_empty():
    assert normalize("") == ""
